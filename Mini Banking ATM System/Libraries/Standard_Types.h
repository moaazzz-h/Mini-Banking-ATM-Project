#ifndef STANDARD_TYPES_H
#define STANDARD_TYPES_H

typedef unsigned char       u8;       // 1 Byte = 8 Bits
typedef signed char         s8;       // 1 Byte = 8 Bits

typedef unsigned short int  u16;      // 2 Bytes = 16 Bits
typedef signed short int    s16;      // 2 Bytes = 16 Bits

typedef unsigned int        u32;      // 4 Bytes = 32 Bits
typedef signed int          s32;      // 4 Bytes = 32 Bits

typedef unsigned long long int  u64;  // 8 Bytes = 64 Bits
typedef signed long long int    s64;  // 8 Bytes = 64 Bits

typedef float               f32;      // 4 Bytes = 32 Bits
typedef double              f64;      // 8 Bytes = 64 Bits

typedef long double         f128;     // 16 Bytes = 128 Bits

#endif // STANDARD_TYPES_H

